verificar("Quien gestiona el personal da de alta vendedores", st == 201 and r["role"] == "VENDEDOR", (st, r))
NUEVO = r["id"]

print("\n=== Sin ser administrador no se llega a administrador ===")
st, r = jefa.api("POST", "/personal", {"name": "Otro Admin", "user": "otroadmin", "pass": "Temporal123", "role": "ADMINISTRADOR"})
verificar("No crea administradores → 403", st == 403 and r.get("codigo") == "PERSONAL_SIN_PERMISO", (st, r))
jefa_id = int(sql("select id from usuarios where \"user\" = 'jefa'"))
st, r = jefa.api("PUT", f"/personal/{jefa_id}", {"name": "Jefa", "user": "jefa", "role": "ADMINISTRADOR"})
verificar("No se asciende a sí misma → 403", st == 403, (st, r))
st, r = jefa.api("PUT", f"/personal/{ADMIN_ID}", {"name": "Administrador", "user": "admin", "pass": "TomadoPorJefa1"})
verificar("No restablece la clave del administrador → 403", st == 403, (st, r))
verificar("…y la clave del administrador sigue siendo la suya", entrar("admin", "AdminPersonal2026").api("GET", "/auth/me")[0] == 200)
st, r = jefa.api("DELETE", f"/personal/{ADMIN_ID}")
