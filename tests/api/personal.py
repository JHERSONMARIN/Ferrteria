st, r = jefa.api("PUT", f"/personal/{NUEVO}", {"name": "Nuevo Vendedor", "user": "nuevo", "role": "CAJERO", "modules": ["caja"]})
verificar("Sí cambia el rol de un empleado que no es administrador", st == 200 and r["role"] == "CAJERO", (st, r))
st, r = admin.api("POST", "/personal", {"name": "Segunda Admin", "user": "admin2", "pass": "Temporal123", "role": "ADMINISTRADOR"})
verificar("El administrador sí crea administradores", st == 201 and r["role"] == "ADMINISTRADOR", (st, r))

print("\n=== Cambios y bajas ===")
