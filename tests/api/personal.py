st, r = admin.api("POST", "/personal", {"name": "X", "user": "rolraro", "pass": "Temporal123", "role": "SUPERUSUARIO", "modules": ["pos"]})
verificar("Un rol inexistente → 400 (no un error del servidor)", st == 400 and "Rol no válido" in r.get("error", ""), (st, r))
st, r = admin.api("POST", "/personal", {"name": "X", "user": "sinmodulo", "pass": "Temporal123", "role": "VENDEDOR", "modules": ["farmacia"]})
verificar("Un módulo que la empresa no tiene → 400", st == 400 and "no están disponibles" in r.get("error", ""), (st, r))
st, r = admin.api("POST", "/personal", {"name": "Jefa", "user": "JEFA2", "pass": "123", "role": "VENDEDOR"})
verificar("Clave débil → 400", st == 400, (st, r))
